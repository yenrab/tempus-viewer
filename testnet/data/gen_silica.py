"""Emits Silica units for the reply of each named published name, from the same data gen.py writes as .etf.

  python3 gen_silica.py --names home --module viewer_replies --out DIR         the content node's unit (+ .atoms)
  python3 gen_silica.py --names home --stub --module bridge_fns --out DIR     the bridge's unit: same types, no data
Each run also writes MODULE.atoms (tags and keys) and MODULE.trust (`export viewer NAME 0 MODULE@NAME args string result T`).

The type of a reply is inferred from the data (one inline sum of tagged tuples, each carrying one record, as ruled
2026-11-24) over ALL the names given, so a name needs nothing but being listed. Every name's function is `NAME(args:
List[string, mem(normal)]) -> (:ok, REPLY) | (:error, atom)`; REPLY is the same type for every name (the one
vocabulary type), so the content node and the bridge agree on it. Asserts text is ASCII (Silica string literals here
are written with simple escapes only). Not for the paged names yet (events.N, samples.N).

TEMPUS-viewer TEST data only."""
import argparse, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from etf import Atom
import gen

STR, INT, BOOL = "string", "int64", "boolean"


# ---- type inference ----------------------------------------------------------------------------------------------
# a type is: "string" | "int64" | "boolean" | ("list", T or None) | ("rec", {k: T}) | ("sum", {tag: T}) | None (unknown)
def infer(x):
    if isinstance(x, bool): return BOOL
    if isinstance(x, int): return INT
    if isinstance(x, (str, bytes)): return STR
    if isinstance(x, tuple):
        assert len(x) == 2 and isinstance(x[0], Atom), x
        return ("sum", {str(x[0]): infer(x[1])})
    if isinstance(x, dict): return ("rec", {k: infer(v) for k, v in x.items()})
    if isinstance(x, list):
        e = None
        for i in x: e = unify(e, infer(i))
        return ("list", e)
    raise TypeError(x)


def unify(a, b):
    if a is None: return b
    if b is None: return a
    if isinstance(a, str) or isinstance(b, str):
        assert a == b, (a, b)
        return a
    assert a[0] == b[0], (a, b)
    if a[0] == "list": return ("list", unify(a[1], b[1]))
    if a[0] == "rec":
        assert set(a[1]) == set(b[1]), (a, b)
        return ("rec", {k: unify(a[1][k], b[1][k]) for k in a[1]})
    out = dict(a[1])
    for t, ty in b[1].items(): out[t] = unify(out.get(t), ty)
    return ("sum", out)


def render(t):
    if t is None: return STR          # an element type seen only as empty lists: string
    if isinstance(t, str): return t
    if t[0] == "list": return "List[%s, mem(normal)]" % render(t[1])
    if t[0] == "rec": return "{ " + ", ".join("%s: %s" % (k, render(v)) for k, v in sorted(t[1].items())) + " }"
    return " | ".join("(:%s, %s)" % (tag, render(ty)) for tag, ty in t[1].items())


def atoms_of(t, acc):
    if t is None or isinstance(t, str): return
    if t[0] == "list": atoms_of(t[1], acc)
    elif t[0] == "rec":
        for k, v in t[1].items(): acc.add(k); atoms_of(v, acc)
    else:
        for tag, v in t[1].items(): acc.add(tag); atoms_of(v, acc)


# ---- values ------------------------------------------------------------------------------------------------------
def lit(x):
    if isinstance(x, bool): return "true" if x else "false"
    if isinstance(x, int): return str(x)
    if isinstance(x, (str, bytes)):
        s = x.decode() if isinstance(x, bytes) else x
        assert s.isascii() and "\n" not in s, s
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(x, tuple): return "(:%s, %s)" % (x[0], lit(x[1]))
    if isinstance(x, dict): return "{ " + ", ".join("%s: %s" % (k, lit(v)) for k, v in sorted(x.items())) + " }"
    if isinstance(x, list): return "[" + ", ".join(lit(i) for i in x) + "]"
    raise TypeError(x)


def collect(names):
    ty, data = None, {}
    for n in names:
        cs = gen.REPLIES[n]["commands"]
        data[n] = cs
        ty = unify(ty, infer(cs))
    return ty, data


def emit(names, module, stub):
    ty, data = collect(names)
    T = render(ty)
    L = ["// Generated by testnet/data/gen_silica.py from testnet/data/gen.py's data (%s). Do not edit." % ("a stub: the types only" if stub else "names: " + ", ".join(names)),
         "// TEST data about an invented network.", "module %s;" % module, "use bees_atoms;", ""]
    L += ["export %s/1;" % n for n in names] + [""]
    for n in names:
        if stub:
            L.append("fn %s(xs: List[string, mem(normal)]) -> (:ok, %s) | (:error, atom) { (:error, bees_atoms@a_unsupported()) }" % (n, T))
            continue
        L.append("fn %s(xs: List[string, mem(normal)]) -> (:ok, %s) | (:error, atom) {" % (n, T))
        L.append("    sequence proc[mem(normal)]")
        L.append("        cs: %s <- %s" % (T, lit(data[n])))
        L.append("    produces pure (:ok, cs) end")
        L.append("}")
    ats = set(); atoms_of(ty, ats)
    # true and false: the atoms a boolean field is written as; a TRUST frame's atom policy (bees_trust_frame@atom_held) refuses
    # an atom that is not in the program's table, so they must be in it (found: result frames with a boolean were refused, code 10)
    return "\n".join(L) + "\n", T, sorted(ats | {"true", "false"})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--names", required=True)
    ap.add_argument("--module", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--stub", action="store_true")
    ap.add_argument("--also-atoms-for", action="append", default=[], help="another unit that writes the reply type (BEES's generated bees_trust_mfa does): its .atoms manifest gets the same atoms (D30)")
    a = ap.parse_args()
    names = a.names.split(",")
    for n in names: assert n in gen.REPLIES and not gen.REPLIES[n].get("pages"), n
    text, T, ats = emit(names, a.module, a.stub)
    os.makedirs(a.out, exist_ok=True)
    open(os.path.join(a.out, a.module + ".silica"), "w").write(text)
    for unit in [a.module] + a.also_atoms_for:
        open(os.path.join(a.out, unit + ".atoms"), "w").write("# written by gen_silica.py: tags and map keys of the reply type\n" + "\n".join(ats) + "\n")
    open(os.path.join(a.out, a.module + ".trust"), "w").write("# written by gen_silica.py\n" + "".join(
        "export viewer %s 0 %s@%s args string result %s\n" % (n, a.module, n, T) for n in names))


if __name__ == "__main__":
    main()
